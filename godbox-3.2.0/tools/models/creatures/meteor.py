ga.box((3, 8, -2), (14, 9.6, 1), lava, rot=("z", -22.5))
ga.box((-13.4, -5, -4), (-11.6, 6, 3), lava, rot=("z", 22.5))
ga.box((10.5, -3, -8), (12.8, 4, 0), lava, rot=("y", 22.5))
ga.box((-8, -3, 10.4), (2, 5, 12.4), lava, rot=("x", 22.5))
ga.box((0, -11.4, -8), (10, -9.6, 3), lava, rot=("z", 22.5))
ga.box((-9, 3, -10.4), (-1, 8, -8.6), lava, rot=("x", 45))
ga.box((6, 4, -12.4), (12, 6.4, -9), lava, rot=("y", 45))
ga.box((0, 12, 0), (3, 14, 3), hot)                                            # раскалённые пятна
ga.box((-13.8, 1, -2), (-11.8, 3.6, 0.6), hot)
ga.box((12.2, -1, -4), (14.2, 1.6, -1.4), hot)
ga.box((-4, 8.4, -10.8), (-1, 10.4, -8.6), hot)
ga.box((3, -11.8, -2), (6, -9.8, 1), hot)
ga.box((-4, 0, 11.4), (-1, 2.6, 13.4), hot)
ga.box((12, -9, 3), (14, -7, 5.4), hot)

# ---------------------------------------------------------------- форма B: вытянутый обломок
rb = c2.part("rock")
